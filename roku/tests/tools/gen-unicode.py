#!/usr/bin/env python3
"""Writes source/franchise/FranchiseUnicode.brs: the upper-case mappings and
canonical compositions the port needs to compare and show names as Swift
does (String.uppercased() and String's NFC-based ordering), for the scripts
NxFranchiseLower covers. Roku's UCase isn't Unicode-aware on a TV, and
BrightScript compares raw code points.

    python3 tests/tools/gen-unicode.py      # from roku/

The tables come from this Python's unicodedata; the file records its
Unicode version.
"""
import os, unicodedata

RANGES = [(0x80, 0x24F), (0x370, 0x3FF), (0x400, 0x52F), (0x531, 0x587),
          (0x1E00, 0x1EFF), (0x2160, 0x217F), (0x24B6, 0x24E9), (0xFF21, 0xFF5A)]

def cps():
    for a, b in RANGES:
        yield from range(a, b + 1)

upper, compose = [], []
for cp in cps():
    ch = chr(cp)
    if unicodedata.category(ch) == "Cn":
        continue
    u = ch.upper()
    if u != ch:
        upper.append(f"{cp:x}:" + ".".join(f"{ord(c):x}" for c in u))
    d = unicodedata.decomposition(ch)
    if d and not d.startswith("<"):
        parts = [int(x, 16) for x in d.split()]
        # A canonical pair that NFC recomposes (not a composition exclusion).
        if len(parts) == 2 and unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == ch:
            compose.append(f"{parts[0]:x}.{parts[1]:x}:{cp:x}")

def chunks(items, n=40):
    for i in range(0, len(items), n):
        yield ",".join(items[i:i + n])

def brs_function(name, items, doc):
    body = "\n".join(f'    s = s + "{c},"' for c in chunks(items))
    return f"""' {doc}
function {name}() as String
    s = ""
{body}
    return s
end function
"""

out = f"""' Generated by tests/tools/gen-unicode.py from Unicode {unicodedata.unidata_version}. Do not edit.
'
' Copyright (c) 2026 nostalgex-roku contributors, MIT License.

{brs_function("NxUnicodeUpperTable", upper, "Upper-case mappings: lower:upper[.upper], hex code points, comma-separated.")}
{brs_function("NxUnicodeComposeTable", compose, "Canonical compositions NFC makes: base.mark:composed, hex code points.")}"""
path = os.path.join(os.path.dirname(__file__), "..", "..", "source", "franchise", "FranchiseUnicode.brs")
with open(path, "w") as f:
    f.write(out)
print(f"{len(upper)} upper-case mappings, {len(compose)} compositions")
